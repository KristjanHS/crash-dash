// DB-free unit tests for dump.ts's pure incremental-resume seams (plan Rung 2).
import { describe, expect, it } from "vitest";
import {
  COMPACT_DEAD_FRACTION,
  PART_BYTES,
  compactionDue,
  formatMetaLine,
  parseMetaLine,
  partFileName,
  planResume,
  resumeGuardOk,
  snapshotPartFiles,
  splitIntoParts,
  splitSnapshot,
  staleSnapshotFiles,
  tableLogLine,
  type TableLogEvent,
} from "./dump.js";

const meta = { page: 5000, resumeAfterId: 15000, rows: 15750 };
const metaLine = "-- meta: page=5000 resume_after_id=15000 rows=15750";

function snapshot(rows: number, page: number, resumeAfterId: number, statements: string[]): string {
  return [
    "-- Disaster-recovery snapshot of prod public.readings.",
    "-- Generated by scripts/backup/dump.ts (npm run backup:data). Restore: docs/reference.md §[dr] Restore procedure.",
    `-- id omitted (GENERATED ALWAYS → regenerates on load). ${page} rows/statement, id-aligned & append-only. Rows: ${rows}.`,
    formatMetaLine({ page, resumeAfterId, rows }),
    "",
    ...statements,
    "",
  ].join("\n");
}

const stmt = (n: number) => `INSERT INTO public.readings (a,b) VALUES ('page${n}');`;

describe("meta line", () => {
  it("round-trips", () => {
    expect(formatMetaLine(meta)).toBe(metaLine);
    expect(parseMetaLine(metaLine)).toEqual(meta);
  });

  it("rejects non-meta lines", () => {
    expect(parseMetaLine("-- id omitted. Rows: 5.")).toBeNull();
    expect(parseMetaLine("-- meta: page=x resume_after_id=1 rows=2")).toBeNull();
    expect(parseMetaLine("")).toBeNull();
  });
});

describe("splitSnapshot", () => {
  it("extracts meta + INSERT statements, ignoring header comments and blanks", () => {
    const { meta: m, statements } = splitSnapshot(snapshot(15750, 5000, 15000, [stmt(1), stmt(2), stmt(3), stmt(4)]));
    expect(m).toEqual(meta);
    expect(statements).toHaveLength(4);
    expect(statements[0]).toBe(stmt(1));
  });

  it("returns null meta for a pre-incremental snapshot", () => {
    const legacy = ["-- Disaster-recovery snapshot.", "-- Rows: 3.", "", stmt(1), ""].join("\n");
    expect(splitSnapshot(legacy).meta).toBeNull();
    expect(splitSnapshot(legacy).statements).toHaveLength(1);
  });
});

describe("resumeGuardOk — the count-guard after SCRIPT-3 relaxed it to `<=`", () => {
  // `maxId` is the table's GLOBAL top id; healthy prod keeps growing it past the resume point.
  const healthy = { expected: 15_000, maxId: 20_000, afterId: 15_000 };

  it.each([
    ["exact match (nothing pruned)", { actual: 15_000 }, true],
    ["shrinkage from the daily prune (the old `===` re-dumped ~118k rows)", { actual: 14_850 }, true],
    ["growth below a fixed resume point", { actual: 15_001 }, false],
    // The old code's -1 "no row" sentinel satisfies `<=` arithmetically — every spelling fails closed.
    ["failed probe: null", { actual: null }, false],
    ["failed probe: -1 sentinel", { actual: -1 }, false],
    ["failed probe: NaN", { actual: Number.NaN }, false],
    ["failed probe: null maxId", { actual: 15_000, maxId: null }, false],
    // Identity restarts at 1: reads as a big prune, the `id > afterId` loop finds nothing, snapshot freezes.
    ["reseeded table (count looks like shrinkage)", { actual: 300, maxId: 300 }, false],
    ["fully pruned range, table kept growing", { actual: 0 }, true],
    ["zero rows AND collapsed top id (wiped table)", { actual: 0, maxId: 0 }, false],
    // maxId is the GLOBAL max: a prune may delete the row at exactly afterId.
    ["boundary row at afterId pruned", { actual: 14_999 }, true],
  ] as const)("%s → %s", (_label, over, ok) => {
    expect(resumeGuardOk({ ...healthy, ...over })).toBe(ok);
  });
});

describe("compactionDue — a resume is abandoned once the kept pages' dead fraction reaches the threshold", () => {
  const expected = 100_000;
  const dead = Math.ceil(expected * COMPACT_DEAD_FRACTION);

  it("returns the dead count at exactly the threshold and above", () => {
    expect(compactionDue({ expected, actual: expected - dead })).toBe(dead);
    expect(compactionDue({ expected, actual: 0 })).toBe(expected);
  });

  it("returns null one row under the threshold, with no dead rows, and on an empty kept set", () => {
    expect(compactionDue({ expected, actual: expected - dead + 1 })).toBeNull();
    expect(compactionDue({ expected, actual: expected })).toBeNull();
    expect(compactionDue({ expected: 0, actual: 0 })).toBeNull();
  });
});

describe("planResume", () => {
  it("happy path: keeps the full pages, drops the trailing partial", () => {
    const plan = planResume(snapshot(15750, 5000, 15000, [stmt(1), stmt(2), stmt(3), stmt(4)]), 5000);
    expect(plan).toEqual({ full: false, afterId: 15000, fullPages: 3, keep: [stmt(1), stmt(2), stmt(3)] });
  });

  it("keeps ALL statements when rows divide evenly (no partial)", () => {
    const plan = planResume(snapshot(10000, 5000, 10000, [stmt(1), stmt(2)]), 5000);
    expect(plan).toEqual({ full: false, afterId: 10000, fullPages: 2, keep: [stmt(1), stmt(2)] });
  });

  it("small table (rows < page): resume degenerates to a full dump from id 0", () => {
    const plan = planResume(snapshot(42, 5000, 0, [stmt(1)]), 5000);
    expect(plan).toEqual({ full: false, afterId: 0, fullPages: 0, keep: [] });
  });

  it("page-size change forces a full re-dump (self-heals future PAGE bumps)", () => {
    const plan = planResume(snapshot(15750, 1000, 15000, [stmt(1)]), 5000);
    expect(plan).toMatchObject({ full: true });
  });

  it("missing meta line forces a full re-dump", () => {
    const legacy = ["-- Disaster-recovery snapshot.", "", stmt(1), ""].join("\n");
    expect(planResume(legacy, 5000)).toMatchObject({ full: true });
  });

  it("fewer statements than full pages (truncated file) forces a full re-dump", () => {
    const plan = planResume(snapshot(15750, 5000, 15000, [stmt(1), stmt(2)]), 5000);
    expect(plan).toMatchObject({ full: true });
  });

  it("kept statement not ending in ';' (truncated mid-statement) forces a full re-dump", () => {
    const truncated = stmt(2).slice(0, -20); // cut inside the last full page's statement
    expect(planResume(snapshot(15750, 5000, 15000, [stmt(1), truncated, stmt(3), stmt(4)]), 5000)).toMatchObject({
      full: true,
    });
  });

  it("multi-line INSERT (newline inside a value) forces a full re-dump, not a silent truncation", () => {
    // splitSnapshot only sees the first physical line of a multi-line statement — the
    // ';'-guard must reject it rather than keep the truncated head verbatim.
    const multiLine = `INSERT INTO public.readings (a,b) VALUES ('line1\nline2');`;
    const plan = planResume(snapshot(15750, 5000, 15000, [stmt(1), multiLine, stmt(3), stmt(4)]), 5000);
    expect(plan).toMatchObject({ full: true });
  });

  it("empty snapshot (rows=0): resume degenerates to a full dump from id 0", () => {
    expect(planResume(snapshot(0, 5000, 0, []), 5000)).toEqual({ full: false, afterId: 0, fullPages: 0, keep: [] });
  });
});

describe("splitIntoParts — bounded snapshot files (2026-09-05: readings.sql hit 106 MB, GitHub rejected the push)", () => {
  const st = (n: number, size = 10) => `${String(n).padStart(2, "0")}${"x".repeat(size - 3)};`; // exactly `size` bytes

  it("packs statements greedily under the byte bound, in order", () => {
    // 4 × 10 bytes (+1 newline each) under a 25-byte bound → [2, 2]
    expect(splitIntoParts([st(1), st(2), st(3), st(4)], 25)).toEqual([[st(1), st(2)], [st(3), st(4)]]);
  });

  it("part boundaries are a function of the PREFIX — appending statements never moves an earlier cut", () => {
    // Full pages are kept verbatim across dumps, so this is what keeps every part but the last
    // byte-identical day to day (git stores one blob per part, and the daily delta stays tiny).
    const base = [st(1), st(2), st(3)];
    const before = splitIntoParts(base, 25);
    const after = splitIntoParts([...base, st(4), st(5)], 25);
    expect(after.slice(0, before.length - 1)).toEqual(before.slice(0, -1));
    expect(after[before.length - 1]!.slice(0, before.at(-1)!.length)).toEqual(before.at(-1));
  });

  it("an empty statement list still yields one (header-only) part", () => {
    expect(splitIntoParts([], 25)).toEqual([[]]);
  });

  it("REFUSES a single statement over the bound — a part is only bounded if its statements are", () => {
    // The guard must be able to fire — and did: on 2026-09-05 a 100-row alert_log page came back as
    // 49.6 MB (panel_state ~576 KB/row before the 20260905150000 compaction), so alert_log paged at 20 until
    // the rows shrank to ~25 KB (now 500). A PAGE bump that outgrows the bound
    // fails here, naming the fix, not at GitHub's pre-receive hook.
    expect(() => splitIntoParts([st(1, 30)], 25)).toThrow(/PAGE/);
  });

  it("the bound leaves headroom under GitHub's limits (warn 50 MB, reject 100 MiB)", () => {
    expect(PART_BYTES).toBeLessThanOrEqual(45 * 1024 * 1024);
  });
});

describe("snapshot part files", () => {
  it("names parts zero-padded so lexical order is numeric order", () => {
    expect(partFileName("readings", 0)).toBe("readings.000.sql");
    expect(partFileName("readings", 12)).toBe("readings.012.sql");
  });

  it("selects this table's parts only, in numeric order, ignoring the legacy single file", () => {
    const names = ["readings.sql", "readings.010.sql", "alert_log.000.sql", "readings.000.sql", "readings.002.sql", "notes.txt"];
    expect(snapshotPartFiles(names, "readings")).toEqual(["readings.000.sql", "readings.002.sql", "readings.010.sql"]);
    expect(snapshotPartFiles(["readings.sql"], "readings")).toEqual([]);
  });

  it("stale = the legacy single file + parts beyond the new count, never another table's files", () => {
    const names = ["readings.sql", "readings.000.sql", "readings.001.sql", "readings.002.sql", "alert_log.000.sql"];
    expect(staleSnapshotFiles(names, "readings", ["readings.000.sql", "readings.001.sql"])).toEqual([
      "readings.sql",
      "readings.002.sql",
    ]);
  });
});

describe("tableLogLine", () => {
  const events: TableLogEvent[] = [
    { kind: "compaction", dead: 4321, expected: 9876 },
    { kind: "resume", afterId: 4321, fullPages: 9876, pruned: 55 },
    { kind: "rejected", why: "4321 rows below id 9876" },
    { kind: "wrote", rows: 4321, parts: 9876, secs: "5.5" },
  ];

  it("a CI (public log) line names the table and carries no number; the local line keeps the counts", () => {
    for (const ev of events) {
      expect(tableLogLine("readings", ev, true)).toMatch(/^\[backup\] (wrote )?readings\b\D*$/);
      expect(tableLogLine("readings", ev, false)).toMatch(/4321/);
    }
  });
});
