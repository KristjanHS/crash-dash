#!/usr/bin/env bash
# Dump the local backfilled data → supabase/seed.sql so it survives `supabase db
# reset` (which drops + re-applies migrations clean, wiping all rows). Supabase
# auto-loads seed.sql after migrations on every reset (config.toml [db.seed]).
#
# Format: batched multi-row INSERTs (1000 rows/statement), one statement per line.
#   - Plain INSERTs, NOT `COPY ... FROM stdin`: the CLI's seed loader splits on
#     `;` and can't stream COPY data (it chokes on the first data row).
#   - The id column is OMITTED (every table's id is GENERATED ALWAYS AS IDENTITY),
#     so identity regenerates on load — no OVERRIDING SYSTEM VALUE, no setval fix-up,
#     and later `npm start` inserts never collide with a restored sequence.
#   - Each value is rendered as quote_nullable(col::text): a correctly-quoted text
#     literal that Postgres assignment-casts back to the column's real type on load,
#     so one generic renderer covers every column type. extra_float_digits=3 keeps
#     float values exactly round-trippable.
#
# seed.sql is gitignored (local-only; CI resets stay empty/fast). Re-run after any
# fresh backfill to refresh the snapshot:  npm run seed:dump
#
set -euo pipefail
cd "$(dirname "$0")/../.."

DB=supabase_db_crash-dash
OUT=supabase/seed.sql
TABLES=(readings alert_log calibration)
PSQL=(docker exec -i "$DB" psql -U postgres -d postgres -At)

{
  echo "-- Local backfill snapshot — generated by scripts/preview/dump-seed.sh. Gitignored."
  echo "-- Auto-loaded by \`supabase db reset\` (config.toml [db.seed]); re-dump after re-backfill."
  echo "-- Batched INSERTs, id omitted (GENERATED ALWAYS → identity regenerates on load)."
  for t in "${TABLES[@]}"; do
    cols_raw=$("${PSQL[@]}" -c \
      "select column_name from information_schema.columns
        where table_schema='public' and table_name='$t' and is_identity='NO'
        order by ordinal_position;")
    [ -n "$cols_raw" ] || { echo "::error:: public.$t has no columns — missing table?" >&2; exit 1; }
    mapfile -t COLARR <<<"$cols_raw"
    n=$("${PSQL[@]}" -c "select count(*) from public.$t;")
    (( n > 0 )) || { echo ""; echo "-- $t: 0 rows (skipped)"; continue; }

    cols=$(IFS=,; echo "${COLARR[*]}")
    # Per-row tuple: quote_nullable("col"::text) for every column, comma-joined.
    vexpr=""
    for c in "${COLARR[@]}"; do
      [ -n "$vexpr" ] && vexpr="$vexpr||','||"
      vexpr="${vexpr}quote_nullable(\"$c\"::text)"
    done

    echo ""
    echo "-- $t: $n row(s)"
    # grep keeps only the INSERT statements — drops psql's "SET" command tag and any
    # blank lines so the seed is pure executable SQL for the CLI loader.
    "${PSQL[@]}" -c "
      set extra_float_digits = 3;
      select 'INSERT INTO public.$t ($cols) VALUES ' || string_agg('(' || $vexpr || ')', ',') || ';'
        from (select *, (row_number() over (order by id) - 1) / 1000 as _grp from public.$t) s
       group by _grp
       order by _grp;" | grep '^INSERT INTO'
  done
} > "$OUT"

rows=$("${PSQL[@]}" -c "select (select count(*) from readings)||' readings, '||(select count(*) from alert_log)||' alerts, '||(select count(*) from calibration)||' calib'")
echo "wrote $OUT ($(du -h "$OUT" | cut -f1)) — $rows"
